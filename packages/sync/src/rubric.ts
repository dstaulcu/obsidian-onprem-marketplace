import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import { join } from "node:path";

/**
 * The rubric: the checks applied to every plugin version, kept as data so people can read, review and extend it
 * through a pull request. rules.json holds the deterministic checks (each with examples that run as tests);
 * review-prompt.md holds what the model is asked to look for. Safety wording that defends the reviewer against
 * hostile input stays in code (review.ts) so a rubric change cannot weaken it.
 */
export interface Rule {
  id: string;
  title: string;
  severity: "high" | "medium";
  pattern: string;
  flags?: string;
  why: string;
  examples: { match: string[]; noMatch: string[] };
}
export interface CompiledRule extends Rule { re: RegExp }
export interface Rubric {
  name: string;
  /** name@hash of the rules and prompt: changes whenever any check changes, so stale reviews are detected. */
  version: string;
  rules: CompiledRule[];
  prompt: string;
}

/** Example strings may contain <<x*N>> which expands to N copies of x (for long-pattern rules). */
export const expandExample = (s: string) => s.replace(/<<(.)\*(\d+)>>/g, (_m, c: string, n: string) => c.repeat(Number(n)));

const ID_RE = /^[a-z0-9][a-z0-9-]*$/;

export function validateRules(raw: unknown): string[] {
  const errs: string[] = [];
  const rules = (raw as { rules?: unknown })?.rules;
  if (!Array.isArray(rules) || !rules.length) return ["rules must be a non-empty array"];
  const seen = new Set<string>();
  rules.forEach((r: Partial<Rule>, i) => {
    const at = `rule ${r?.id ?? i}`;
    if (!r || typeof r.id !== "string" || !ID_RE.test(r.id)) errs.push(`${at}: id must be lowercase letters, digits, dashes`);
    else if (seen.has(r.id)) errs.push(`${at}: duplicate id`); else seen.add(r.id);
    if (typeof r?.title !== "string" || !r.title.trim()) errs.push(`${at}: missing title`);
    if (r?.severity !== "high" && r?.severity !== "medium") errs.push(`${at}: severity must be high or medium`);
    if (typeof r?.why !== "string" || r.why.trim().length < 20) errs.push(`${at}: why must explain the risk (20+ chars)`);
    if (typeof r?.pattern !== "string") errs.push(`${at}: missing pattern`);
    else { try { new RegExp(r.pattern, r.flags ?? "g"); } catch (e) { errs.push(`${at}: bad pattern: ${(e as Error).message}`); } }
    if (!r?.examples?.match?.length) errs.push(`${at}: needs at least one examples.match`);
    if (!r?.examples?.noMatch?.length) errs.push(`${at}: needs at least one examples.noMatch`);
  });
  return errs;
}

const compile = (r: Rule): CompiledRule => ({ ...r, re: new RegExp(r.pattern, (r.flags ?? "g").includes("g") ? (r.flags ?? "g") : (r.flags ?? "") + "g") });

/** Runs a rule's own examples and a speed guard (patterns run on megabyte bundles). Returns failures. */
export function testRule(rule: CompiledRule): string[] {
  const fails: string[] = [];
  const hit = (s: string) => { rule.re.lastIndex = 0; return rule.re.test(s); };
  for (const m of rule.examples.match) if (!hit(expandExample(m))) fails.push(`${rule.id}: should match: ${m.slice(0, 60)}`);
  for (const n of rule.examples.noMatch) if (hit(expandExample(n))) fails.push(`${rule.id}: should NOT match: ${n.slice(0, 60)}`);
  const big = "a(".repeat(100_000) + " ".repeat(50_000) + "\"".repeat(50_000);
  const t = Date.now(); hit(big);
  if (Date.now() - t > 500) fails.push(`${rule.id}: too slow on a 300KB adversarial input (possible catastrophic backtracking)`);
  return fails;
}

export async function loadRubric(dir: string): Promise<Rubric> {
  let raw: { name?: string; rules?: Rule[] };
  try { raw = JSON.parse(await readFile(join(dir, "rules.json"), "utf8")); }
  catch (e) { throw new Error(`cannot read rubric at ${dir}: ${(e as Error).message}`); }
  const errs = validateRules(raw);
  if (errs.length) throw new Error(`invalid rubric ${dir}:\n  ` + errs.join("\n  "));
  const prompt = await readFile(join(dir, "review-prompt.md"), "utf8");
  const rules = raw.rules!.map(compile);
  const canon = JSON.stringify(rules.map((r) => [r.id, r.severity, r.pattern, r.re.flags])) + "\n" + prompt;
  const name = raw.name ?? "custom";
  return { name, version: `${name}@${createHash("sha256").update(canon).digest("hex").slice(0, 10)}`, rules, prompt };
}

/** Markdown page describing every check, generated from the data so docs cannot drift from behaviour. */
export function renderRubricDoc(r: Rubric): string {
  const L = [
    "# Concepts: The Review Rubric", "",
    "_Generated by `om-sync rubric` from `rubric/`. Do not edit by hand; change the rubric files instead._", "",
    `Rubric **${r.name}**, version \`${r.version}\`. Every review record and report names this version. Any change to a`,
    "rule or to the model instructions changes the version, which makes earlier reviews count as stale.", "",
    "A review has two parts:", "",
    "1. **Deterministic checks** (below). Plain pattern rules run in code on `main.js`. They are not AI and cannot be",
    "   talked out of a finding. A **high** hit means the verdict can never be `pass`; a **medium** hit is listed for a",
    "   human to judge.",
    "2. **Model review.** Claude Code reads the evidence and applies the instructions further down. The final verdict is",
    "   the worse of the two.", "",
    "## Deterministic checks", "",
    "| Check | Severity | Why it matters |", "|---|---|---|",
    ...r.rules.map((x) => `| **${x.title}**<br>\`${x.id}\` | ${x.severity} | ${x.why.replace(/\|/g, "\\|")} |`),
    "", "Also reported on every review (no verdict effect): hosts referenced in the code, and what changed since the",
    "previous version (new check hits, new hosts, size).", "",
    "## Model instructions", "", "Quoted verbatim from `rubric/review-prompt.md`:", "",
    ...r.prompt.trim().split("\n").map((l) => (l ? "> " + l : ">")), "",
    "## Fixed safety rules (in code, not part of the rubric)", "",
    "- Everything from the plugin is treated as untrusted data; instructions inside it are ignored and flagged.",
    "- The model has no tools, runs from an empty directory, and must answer in a fixed schema.",
    "- Malformed model output is recorded as `error`, never as a pass.",
    "- Large bundles get excerpts only, and the report says the coverage is partial.", "",
    "## Contributing a check", "",
    "See `rubric/README.md`. Short version: add a rule with examples, run `npm test`, open a pull request.", "",
  ];
  return L.join("\n");
}
